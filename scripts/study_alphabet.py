import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "models" / "zipformer_p-arabic-v3"
OUT = ROOT / "docs" / "phonetic_alphabet.md"

MEANING = {
    "َ": "fatha, short a", "ُ": "damma, short u", "ِ": "kasra, short i",
    "ا": "long a (alif madd); run length = beats", "ۥ": "long u (waw madd); run length = beats",
    "ۦ": "long i (ya madd); run length = beats",
    "ڇ": "qalqalah echo, written after a sakin ق ط ب ج د",
    "ں": "hidden noon with ghunna (ikhfaa), always 3 symbols",
    "۾": "hidden meem with ghunna (ikhfaa shafawi, and iqlab: noon turned meem before ب), always 3 symbols",
    "ۜ": "saktah, a short breathless pause (75:27, 83:14)",
    "ٲ": "tasheel, softened second hamza (41:44 ءَاَعْجَمِىٌّ)",
    "۪": "imalah, a towards e (11:41 مَجْر۪ىٰهَا)",
    "ـ": "lengthened imalah vowel (11:41)",
    "ؙ": "ishmam, lip rounding (12:11 تَأْمَنَّا); unused in the reference",
    "ء": "hamza, glottal stop (also hamzat al-wasl when pronounced)",
}


def runs(text, ch):
    return Counter(len(m.group()) for m in re.finditer(re.escape(ch) + "+", text))


def examples(ref, pattern, n=2, text_pattern=None):
    out = []
    for key, v in ref.items():
        words, ph = v["aya_text"].split(), v["aya_phonemes_list"]
        if len(words) == len(ph):
            for i, (w, p) in enumerate(zip(words, ph)):
                if (text_pattern and re.search(text_pattern, w)) or (not text_pattern and re.search(pattern, p)):
                    nxt = f" {words[i + 1]}" if text_pattern and i + 1 < len(words) else ""
                    pnx = f" {ph[i + 1]}" if text_pattern and i + 1 < len(ph) else ""
                    out.append(f"{key} {w}{nxt} → `{p}{pnx}`")
                    if len(out) >= n:
                        return out
        elif not text_pattern:
            for p in ph:
                if re.search(pattern, p):
                    out.append(f"{key} `{p}`")
                    if len(out) >= n:
                        return out
    return out


def main() -> int:
    rows = []
    for line in (MODEL / "tokens.txt").read_text(encoding="utf-8").splitlines():
        sym, _, idx = line.rpartition(" ")
        rows.append((int(idx), sym))
    rows.sort()
    ref = json.loads((MODEL / "ordered_quran_phonemes.json").read_text(encoding="utf-8"))
    text = " ".join(v["aya_phoneme"] for v in ref.values())
    chars = sorted({c for _, s in rows if s != "<blank>" for c in s})
    freq = Counter(c for c in text if not c.isspace())
    blank = next(i for i, s in rows if s == "<blank>")

    L = ["# The phonetic alphabet of zipformer_p-arabic-v3.1", "",
         "Generated by `scripts/study_alphabet.py` from `tokens.txt` and `ordered_quran_phonemes.json`.", "",
         "## Tokens and CTC", "",
         f"`tokens.txt` has {len(rows)} entries: {len(rows) - 1} output symbols and the CTC blank "
         f"`<blank>` at id {blank}. The ids in `phoneme_units.json` put the blank at 0, so they are shifted "
         "by one against the model's output layer and must not be used for decoding.", "",
         "The model emits one distribution over the 251 entries every 40 ms frame. Greedy CTC decoding takes "
         "the best entry per frame, merges consecutive repeats, then removes blanks. The blank is what lets "
         "the model say the same symbol twice in a row (`ا <blank> ا`) and what it outputs between sounds.", "",
         f"The tokens are built from only {len(chars)} characters. Apart from the single characters, they are "
         "merged chunks, the way BPE works: a letter with its vowel (`بَ`), a doubled letter with its vowel "
         "(`ببَ`), or a whole madd (`اااا`). One sound can therefore be split into tokens in more than one way, "
         "so the app compares phonemes character by character, not token by token.", "",
         "## The characters", "",
         "| char | meaning | count in reference | run lengths (length: count) |", "|:---:|:---|---:|:---|"]
    for c in chars:
        meaning = MEANING.get(c, "consonant")
        rl = ", ".join(f"{k}: {v}" for k, v in sorted(runs(text, c).items()))
        L.append(f"| {c} | {meaning} | {freq[c]} | {rl} |")

    L += ["", "## How the script writes recitation", "",
          "**Letters.** Each consonant is its Arabic letter. Hamzat al-wasl is written as `ء` with its vowel "
          "when it is pronounced at the start, and dropped when it is joined to the previous word.", "",
          "**Short vowels.** Fatha, damma and kasra follow their consonant. **Sukun** has no symbol: a "
          "consonant with no vowel after it is sakin.", ""]
    L += [f"- {e}" for e in examples(ref, r"^بِسمِ$", 1) + examples(ref, r"^نَعبُدُ$", 1)]
    L += ["", "**Shadda** is the letter written twice. With noon and meem the gemination also carries a "
          "2-beat ghunna, so they appear 4 times.", ""]
    L += [f"- {e}" for e in examples(ref, r"ببِ", 1) + examples(ref, r"^ءِننننَ$", 1)]
    L += ["", "**Tanween** is written as the noon it sounds like, then follows the noon rules. At a stop, "
          "tanween fath becomes a 2-beat alif and the other tanween are dropped.", ""]
    L += [f"- {e}" for e in examples(ref, None, 2, text_pattern=r"[ً-ࣰٍ-ࣲ][^ ]*$")]
    last = [f"{k} {v['aya_text'].split()[-1]} → `{v['aya_phonemes_list'][-1]}`" for k, v in ref.items()
            if re.search(r"ً|ࣰ", v["aya_text"].split()[-1])][:2]
    L += [f"- at a stop: {e}" for e in last]
    L += ["", "**Madd.** Vowel length is the run length of `ا`, `ۥ` or `ۦ`, one symbol per beat. The "
          "reference only uses 2, 4 and 6: natural madd 2, connected and separated madd 4, and the "
          "obligatory madd lazim 6. A stop on a long vowel before the last letter gives 4.", ""]
    L += [f"- {e}" for e in examples(ref, r"[^ا]اا[^ا]", 1) + examples(ref, r"ۦۦۦۦم$", 1) +
          examples(ref, r"اااااا", 1)]
    L += ["", "## Tajweed rules in the script", "",
          "- **Ghunna** (nasalisation) is length: noon and meem with shadda are 4 symbols, hidden noon/meem 3.",
          "- **Ikhfaa** of noon sakinah or tanween before the 15 ikhfaa letters becomes `ںںں`.",
          "- **Ikhfaa shafawi** (meem before ب) and **iqlab** (noon before ب) both become `۾۾۾`.",
          "- **Idgham** with ghunna into و or ي shows as a tripled و or ي; into ن or م as 4 of them; "
          "without ghunna into ل or ر as a doubled letter.",
          "- **Qalqalah** is `ڇ` written after a sakin ق ط ب ج د.",
          "- **Gemination** (shadda) is a doubled consonant.",
          "- Rare Hafs features have their own marks: saktah `ۜ`, tasheel `ٲ`, imalah `۪`.", ""]
    for title, pat in [("Ikhfaa", r"ںںں"), ("Iqlab / ikhfaa shafawi", r"۾۾۾ب"), ("Idgham into و", r"[َُِ]وووَ"),
                       ("Idgham into ي", r"[َُِ]يييَ|[^َُِ ]?ييي[َُِ]"), ("Qalqalah", r"قڇ"), ("Saktah", r"ۜ")]:
        L += [f"**{title}**", ""] + [f"- {e}" for e in examples(ref, pat, 2)] + [""]

    L += ["## Al-Fatiha", ""]
    for k in [f"1:{i}" for i in range(1, 8)]:
        L += [f"- **{k}** {ref[k]['aya_text']}  ", f"  `{ref[k]['aya_phoneme']}`"]
    L += ["", "## All tokens", "", " ".join(f"`{i}:{s}`" for i, s in rows), ""]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
